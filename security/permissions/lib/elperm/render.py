"""Render sudoers, polkit, pam_access and group-map files from a Policy."""

from __future__ import annotations

import json
import re
from pathlib import Path

from . import __version__
from .policy import Policy
from .util import (ACCESS_CONF, BREAKGLASS_CONF, GROUPMAP, MANIFEST, POLKIT_ROLES,
                   SUDOERS_ROLES, Context, ElPermError, atomic_write, iso, pretty_json,
                   read_json, sha256_bytes, unique)

MODE_NORMAL = "normal"
MODE_DEGRADED = "degraded"

HEADER = ("Generated by el-perm-render {ver} (enterprise-linux). DO NOT EDIT:\n"
          "local changes are overwritten and reported as drift by `el-perm-render --check`.\n"
          "Policy: {name} {version} sha256:{sha}\n"
          "Mode: {mode}")

POLKIT_RESULTS = {
    "yes": "polkit.Result.YES",
    "no": "polkit.Result.NO",
    "auth_self": "polkit.Result.AUTH_SELF",
    "auth_self_keep": "polkit.Result.AUTH_SELF_KEEP",
    "auth_admin": "polkit.Result.AUTH_ADMIN",
    "auth_admin_keep": "polkit.Result.AUTH_ADMIN_KEEP",
}


def _comment(text: str, prefix: str) -> str:
    return "\n".join(f"{prefix} {line}".rstrip() for line in text.splitlines())


def _header(policy: Policy, mode: str, prefix: str) -> str:
    mode_text = mode if mode == MODE_NORMAL else (
        "degraded (offline grace period expired: elevated roles dropped to user)")
    return _comment(HEADER.format(ver=__version__, name=policy.name, version=policy.version,
                                  sha=policy.sha256[:16], mode=mode_text), prefix)


# ------------------------------------------------------------------ sudo impl
def detect_sudo_impl(ctx: Context, policy: Policy) -> str:
    if ctx.sudo_impl:
        return ctx.sudo_impl
    impl = policy.sudo["implementation"]
    if impl != "auto":
        return impl
    if ctx.which("sudo"):
        res = ctx.run(["sudo", "--version"])
        if b"sudo-rs" in (res.stdout or b"") + (res.stderr or b""):
            return "sudo-rs"
    return "sudo"


def user_list(principal: str, deny_groups: list[str]) -> str:
    """sudoers User_List: last match wins, so trailing !%deny entries make
    deny override allow for members of both."""
    return ", ".join([principal] + [f"!%{g}" for g in deny_groups])


def cmnd_spec(commands: list[str], runas: str, nopasswd: bool, option: str = "") -> str:
    tag = "NOPASSWD: " if nopasswd else ""
    opt = f"{option} " if option else ""
    return f"({runas}) {opt}{tag}" + ", ".join(commands)


def render_sudoers(policy: Policy, mode: str, impl: str) -> str:
    deny = policy.posix(policy.login["deny"])
    bg = policy.breakglass["account"]
    out = [_header(policy, mode, "#"), f"# sudo implementation: {impl}", ""]
    out.append("Defaults use_pty")
    out.append(f'Defaults secure_path="{policy.sudo["securePath"]}"')
    if impl == "sudo":
        out.append(f'Defaults logfile="{policy.sudo["logfile"]}"')
    if policy.recording["enabled"]:
        if impl == "sudo":
            out.append("Defaults log_output")
            out.append(f"Defaults iolog_dir={policy.recording['iologDir']}")
        else:
            out.append("# sessionRecording.enabled: sudo-rs has no I/O logging; use tlog "
                       "(tlog-rec-session as the elevated shell). Not rendered here.")
    out.append("")
    out.append("# break-glass: local emergency account, always present, works offline")
    out.append(f"{bg} ALL=(ALL:ALL) ALL")
    for role in policy.roles_by_priority(include_elevated=(mode == MODE_NORMAL)):
        s = role["sudo"]
        if not s:
            continue
        groups = policy.posix(role["groups"])
        out.append("")
        out.append(f"# role {role['name']} <- {', '.join(role['groups'])}")
        for g in groups:
            out.append(f"{user_list('%' + g, deny)} ALL={cmnd_spec(s['commands'], s['runas'], s['nopasswd'])}")
    if mode == MODE_DEGRADED:
        out.append("")
        out.append("# elevated roles omitted: device has not synced within offline.graceDays")
    return "\n".join(out) + "\n"


# --------------------------------------------------------------------- polkit
def js(value) -> str:
    return json.dumps(value)


def polkit_condition(entry: dict) -> str:
    action = entry["action"]
    if action.endswith(".*"):
        conds = [f"action.id.indexOf({js(action[:-1])}) == 0"]
    else:
        conds = [f"action.id == {js(action)}"]
    if entry.get("units"):
        conds.append(f"{js(entry['units'])}.indexOf(action.lookup(\"unit\")) >= 0")
    if entry.get("verbs"):
        conds.append(f"{js(entry['verbs'])}.indexOf(action.lookup(\"verb\")) >= 0")
    return " && ".join(conds)


POLKIT_HELPERS = """\
    function inAny(subject, groups) {
        for (var i = 0; i < groups.length; i++) {
            if (subject.isInGroup(groups[i])) { return true; }
        }
        return false;
    }"""


def render_polkit(policy: Policy, mode: str) -> str:
    deny = policy.posix(policy.login["deny"])
    bg = policy.breakglass["account"]
    roles = policy.roles_by_priority(include_elevated=(mode == MODE_NORMAL))
    admin_ids = [f"unix-user:{bg}"]
    for r in roles:
        if r["polkit"]["admin"]:
            admin_ids += [f"unix-group:{g}" for g in policy.posix(r["groups"])]
    admin_ids = unique(admin_ids)

    o = [_header(policy, mode, "//"),
         "// File sorts before the distro's 50-default.rules so these admin identities",
         "// and role rules are evaluated first (first non-null result wins).",
         "(function () {",
         POLKIT_HELPERS,
         f"    var DENY_GROUPS = {js(deny)};",
         f"    var BREAKGLASS = {js(bg)};",
         "",
         "    polkit.addAdminRule(function (action, subject) {",
         f"        return {js(admin_ids)};",
         "    });",
         "",
         "    polkit.addRule(function (action, subject) {",
         "        // deny overrides allow: login-denied groups get nothing",
         "        if (subject.user != BREAKGLASS && inAny(subject, DENY_GROUPS)) {",
         "            return polkit.Result.NO;",
         "        }",
         "        if (subject.user == BREAKGLASS) {",
         "            return polkit.Result.AUTH_ADMIN_KEEP;",
         "        }"]
    for r in roles:
        pk = r["polkit"]
        if not pk["actions"] and not pk["default"]:
            continue
        body = []
        for entry in pk["actions"]:
            note = f"  // {entry['comment']}" if entry.get("comment") else ""
            body.append(f"if ({polkit_condition(entry)}) {{ return {POLKIT_RESULTS[entry['result']]}; }}{note}")
        if pk["default"]:
            body.append(f"return {POLKIT_RESULTS[pk['default']]};")
        o.append(f"        // role {r['name']} (priority {r['priority']})")
        if r["name"] == "user":
            o += [f"        {line}" for line in body]
        else:
            groups = policy.posix(r["groups"])
            o.append(f"        if (inAny(subject, {js(groups)})) {{")
            o += [f"            {line}" for line in body]
            o.append("        }")
    o += ["        return polkit.Result.NOT_HANDLED;",
          "    });",
          "})();"]
    return "\n".join(o) + "\n"


# ---------------------------------------------------------------- pam_access
def render_access(policy: Policy) -> str:
    bg = policy.breakglass["account"]
    local = unique(policy.login["alwaysAllowLocal"] + [bg])
    o = [_header(policy, MODE_NORMAL, "#"),
         "# pam_access table. First matching line wins. Enable with e.g.:",
         f"#   account required pam_access.so accessfile={ACCESS_CONF}",
         "# Login rules are kept in degraded (offline-expired) mode; only elevation drops.",
         "",
         f"+:{' '.join(local)}:LOCAL"]
    for g in policy.posix(policy.login["deny"]):
        o.append(f"-:({g}):ALL")
    for g in policy.posix(policy.login["allow"]):
        o.append(f"+:({g}):ALL")
    o.append("-:ALL:ALL")
    return "\n".join(o) + "\n"


# ---------------------------------------------------------------- group map
def render_groupmap(policy: Policy) -> str:
    doc = {
        "generatedBy": f"el-perm-render {__version__}",
        "policy": {"name": policy.name, "version": policy.version, "sha256": policy.sha256},
        "explanation": (
            "Rendered rules reference POSIX group names. Directory groups reach NSS through the "
            "identity module (SSSD for AD/IdM, authd or Himmelblau for Entra ID). Each entry shows "
            "the deterministic naming rule applied; if the module names a group differently, set "
            "spec.groupNaming.overrides. `el-perm-render --check-nss` reports names that do not "
            "currently resolve."),
        "groups": policy.namer.mapping(policy.all_group_refs()),
    }
    return pretty_json(doc)


def render_breakglass_conf(policy: Policy) -> str:
    bg = policy.breakglass
    return pretty_json({"account": bg["account"], "passwordLength": bg["passwordLength"],
                        "escrowCommand": bg["escrowCommand"],
                        "rotateAfterUseMinutes": bg["rotateAfterUseMinutes"],
                        "rotateEveryDays": bg["rotateEveryDays"]})


# -------------------------------------------------------------------- render
def render_all(ctx: Context, policy: Policy, mode: str) -> dict[str, tuple[str, int]]:
    impl = detect_sudo_impl(ctx, policy)
    return {
        SUDOERS_ROLES: (render_sudoers(policy, mode, impl), 0o440),
        POLKIT_ROLES: (render_polkit(policy, mode), 0o644),
        ACCESS_CONF: (render_access(policy), 0o644),
        GROUPMAP: (render_groupmap(policy), 0o644),
        BREAKGLASS_CONF: (render_breakglass_conf(policy), 0o644),
    }


def visudo_validator(ctx: Context, warnings: list[str]):
    def _validate(tmp: Path):
        if not ctx.which("visudo"):
            msg = "visudo not found: sudoers syntax NOT validated"
            if ctx.strict_visudo:
                raise ElPermError(msg)
            warnings.append(msg)
            return
        res = ctx.run(["visudo", "-cf", str(tmp)])
        if res.returncode != 0:
            raise ElPermError("visudo rejected rendered sudoers: "
                              + (res.stderr or res.stdout or b"").decode(errors="replace").strip())
    return _validate


def apply(ctx: Context, policy: Policy, mode: str) -> dict:
    files = render_all(ctx, policy, mode)
    warnings: list[str] = []
    manifest_files = {}
    for path, (content, fmode) in files.items():
        validate = visudo_validator(ctx, warnings) if path.startswith("/etc/sudoers.d/") else None
        atomic_write(ctx.path(path), content, fmode, validate=validate)
        manifest_files[path] = {"sha256": sha256_bytes(content.encode()), "mode": oct(fmode)}
    manifest = {
        "generator": f"el-perm-render {__version__}",
        "renderedAt": iso(ctx.now()),
        "policy": {"name": policy.name, "version": policy.version, "sha256": policy.sha256},
        "mode": mode,
        "sudoImplementation": detect_sudo_impl(ctx, policy),
        "files": manifest_files,
    }
    atomic_write(ctx.path(MANIFEST), pretty_json(manifest), 0o644)
    return {"written": sorted(files), "mode": mode, "warnings": warnings, "manifest": manifest}


# --------------------------------------------------------------------- drift
_ADMIN_GROUP_LINE = re.compile(r"^\s*%(sudo|wheel|admin)\s+ALL", re.M)


def check(ctx: Context, policy: Policy, mode: str) -> dict:
    """Compare desired render, on-disk files and the last manifest. No writes.

    modified  -- on-disk content differs from what the manifest says we wrote
                 (someone edited a managed file: drift)
    missing   -- managed file absent
    stale     -- desired render differs from on-disk (policy/mode changed;
                 re-run without --check)
    badmode   -- permissions differ
    unmanaged -- extra files in /etc/sudoers.d not owned by el (standing admin risk)
    """
    files = render_all(ctx, policy, mode)
    manifest = read_json(ctx.path(MANIFEST), default={}) or {}
    mfiles = manifest.get("files", {})
    report = {"modified": [], "missing": [], "stale": [], "badmode": [], "unmanaged": [],
              "warnings": [], "mode": mode}
    for path, (content, fmode) in files.items():
        p = ctx.path(path)
        if not p.exists():
            report["missing"].append(path)
            continue
        disk = p.read_bytes()
        disk_hash = sha256_bytes(disk)
        if path in mfiles and mfiles[path]["sha256"] != disk_hash:
            report["modified"].append(path)
        if disk_hash != sha256_bytes(content.encode()):
            report["stale"].append(path)
        if (p.stat().st_mode & 0o7777) != fmode:
            report["badmode"].append(path)
    sd = ctx.path("/etc/sudoers.d")
    if sd.is_dir():
        for f in sorted(sd.iterdir()):
            n = f.name
            if n in ("50-el-roles", "README") or n.startswith("60-el-jit-") or n.startswith("."):
                continue
            report["unmanaged"].append(f"/etc/sudoers.d/{n}")
    main = ctx.path("/etc/sudoers")
    if main.is_file():
        try:
            m = _ADMIN_GROUP_LINE.findall(main.read_text(errors="replace"))
            if m:
                report["warnings"].append(
                    f"/etc/sudoers grants standing admin to %{', %'.join(sorted(set(m)))}; "
                    "the hardening baseline should remove it")
        except PermissionError:
            report["warnings"].append("/etc/sudoers not readable (run as root)")
    report["drift"] = bool(report["modified"] or report["missing"] or report["stale"]
                           or report["badmode"] or report["unmanaged"])
    return report


def check_nss(ctx: Context, policy: Policy) -> list[str]:
    """Return mapped POSIX groups that NSS does not currently resolve."""
    import grp
    missing = []
    for g in policy.posix(policy.all_group_refs()):
        try:
            grp.getgrnam(g)
        except KeyError:
            missing.append(g)
    return missing
